// ひとつの文だけの直し（文全体がその語のときだけ）
export const WHOLE = { "全": "｜全(ぜん)", "直": "｜直(ちょく)", "技能力": "｜技能力(ぎのうりょく)" };

export function fixRuby(orig, s) {
  if (orig in WHOLE) return WHOLE[orig];
  for (const [re, to] of FIXES) s = s.replace(re, to);
  return s;
}
