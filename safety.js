// 保存する前に、個人情報らしい文字列を伏せ字にする（在留カード番号・電話番号・メール・長い数字）
// 全角の数字・英字・ダッシュは半角にそろえてから調べる（音声の文字起こしでは全角や「の」区切りが多い）
export function mask(text) {
  return String(text ?? "")
    .replace(/[０-９Ａ-Ｚａ-ｚ＠．－]/g, c => String.fromCharCode(c.charCodeAt(0) - 0xFEE0))
    .replace(/[ー―‐−](?=\d)/g, "-")
    .replace(/[A-Za-z]{2}\s?\d{8}\s?[A-Za-z]{2}/g, "＊＊＊")          // 在留カード
    .replace(/\b[A-Za-z]{1,2}\d{7}\b/g, "＊＊＊")                      // 旅券
    .replace(/[\w.+-]+@[\w-]+\.[\w.]+/g, "＊＊＊")
    .replace(/(?:\d[\s-]?){10,}/g, "＊＊＊")                             // 区切りのある長い番号（カード・マイナンバー）
    .replace(/0\d{1,4}(?:[-\s]|の)?\d{1,4}(?:[-\s]|の)?\d{3,4}/g, "＊＊＊")   // 電話（090の1234の5678 も）
    .replace(/〒?\d{3}-\d{4}\b/g, "＊＊＊")                             // 郵便番号
    .replace(/\d{7,}/g, "＊＊＊");
}
