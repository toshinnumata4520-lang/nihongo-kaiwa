const C_KEYS = Object.keys(C).sort((a, b) => b.length - a.length).map(k => k.replace(/[%]/g, "\\$&"));
const NUM_RE = new RegExp(`(\\d+(?:\\.\\d+)?)(万|億|千|百)?(${C_KEYS.join("|")})?(目)?`, "g");
const BIG = { "万": 10000, "億": 1e8, "千": 1000, "百": 100 };
const MONTH = n => n === 4 ? "しがつ" : n === 7 ? "しちがつ" : n === 9 ? "くがつ" : numKana(n) + "がつ";
// そのまま数字で言うと不自然な、決まった読み方の番号
const FIXED_NUM = { "110": "ひゃくとおばん", "119": "ひゃくじゅうきゅうばん" };

function readNumbers(s) {
  s = s.replace(/[０-９]/g, c => String.fromCharCode(c.charCodeAt(0) - 0xFEE0)).replace(/(\d),(?=\d{3})/g, "$1");
  // 決まった番号（警察 110・救急 119）
  s = s.replace(/(^|[^\d])(110|119)(?![\d.])(?!番)/g, (_, a, n) => a + FIXED_NUM[n]);
  // 時刻 9:30 → くじさんじゅっぷん
  s = s.replace(/(\d{1,2})[:：](\d{2})/g, (_, h, m) => C["時"](+h) + (+m ? C["分"](+m) : ""));
  // 範囲 5〜10分 → ごふんから じゅっぷん（前の数にも同じ助数詞を付けて読む）
  s = s.replace(new RegExp(`(\\d+)\\s*[〜～~\\-－]\\s*(\\d+)(${C_KEYS.join("|")})`, "g"), (_, a, b, k) => `${a}${k}から${b}${k}`);
  s = s.replace(/(\d+)\s*[〜～~]\s*(?=\d)/g, "$1から");
  // 試合の点数 3対1 → さんたいいち
  s = s.replace(/(\d+)対(?=\d)/g, "$1たい");
  // 月日：1月1日 → いちがつついたち
  s = s.replace(/(\d{1,2})月(\d{1,2})日/g, (_, m, d) => MONTH(+m) + dayKana(+d, true));
  s = s.replace(/(\d{1,2})月(?![間])/g, (_, m) => +m >= 1 && +m <= 12 ? MONTH(+m) : _);
  s = s.replace(/(?<=(?:月|がつ|つき|げつ)\s*)1日(?!間)/g, "ついたち");   // 毎月 1日 → まいつき ついたち
  s = s.replace(/(\d+)日(間)?/g, (_, d, kan) => dayKana(+d, false) + (kan ? "かん" : ""));
  s = s.replace(NUM_RE, (all, num, big, k, me) => {
    let r;
    // 小数のあとの助数詞は、5 のときの形から「ご」を外したもの（37.5度 → さんじゅうななてんごど）
    if (num.includes(".")) r = decKana(num) + (k ? C[k](5).slice(1) : "");
    else {
      const n = +num * (BIG[big] || 1);
      r = k ? C[k](n) : numKana(n);
    }
    return r + (me ? "め" : "");
  });
  return s;
}

