// 0〜99999999 の数のよみ（ふつうの数え方）
function under10000(n) {
  const th = Math.floor(n / 1000), h = Math.floor(n / 100) % 10, t = Math.floor(n / 10) % 10, o = n % 10;
  let s = "";
  if (th) s += th === 1 ? "せん" : th === 3 ? "さんぜん" : th === 8 ? "はっせん" : D[th] + "せん";
  if (h) s += h === 1 ? "ひゃく" : h === 3 ? "さんびゃく" : h === 6 ? "ろっぴゃく" : h === 8 ? "はっぴゃく" : D[h] + "ひゃく";
  if (t) s += t === 1 ? "じゅう" : D[t] + "じゅう";
  if (o) s += D[o];
  return s;
}
export function numKana(n) {
  n = Math.floor(n);
  if (n === 0) return "ぜろ";
  let s = "";
  const oku = Math.floor(n / 1e8), man = Math.floor(n / 10000) % 10000, r = n % 10000;
  if (oku) s += under10000(oku) + "おく";
  if (man) s += (man === 1 ? "いち" : under10000(man)) + "まん";
  if (r) s += under10000(r);
  return s;
}
const decKana = str => {   // "37.5" → さんじゅうななてんご、"0.5" → れいてんご
  const [a, b] = str.split(".");
  return (a === "0" ? "れい" : numKana(+a)) + "てん" + [...b].map(c => c === "0" ? "ぜろ" : D[+c]).join("");
};

// 助数詞のよみ。f(n) が読みを返す。tail＝最後の位（1〜9 は一の位、10 は「〜じゅう」で終わる、0 はそれ以外）
// over[tail] があればその形（前の位のよみ＋over）、なければ D[tail]/じゅう＋base
function counter(base, over = {}, special = {}) {
  return n => {
    if (special[n] !== undefined) return special[n];
    const o = n % 10, t = Math.floor(n / 10) % 10;
    if (o) {
      const head = numKana(n - o).replace(/^ぜろ$/, "");
      return head + (over[o] ?? D[o] + base);
    }
    if (t) {
      const head = numKana(n - t * 10).replace(/^ぜろ$/, "") + (t === 1 ? "" : D[t]);
      return head + (over[10] ?? "じゅう" + base);
    }
    if (n % 1000 && Math.floor(n / 100) % 10 === 1 && over[100]) return numKana(n - 100).replace(/^ぜろ$/, "") + over[100];
    return numKana(n) + base;
  };
}
