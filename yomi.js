export function speechOf(text, reading = "", ruby = {}) {
  const raw = String(text ?? "");
  const src = String(reading ?? "");
  let kana = "";
  if (src && !KANJI.test(stripRubyReading(src))) kana = stripRubyReading(src);       // 渡された読み（ふりがなの形でも読みだけにする）
  else if (SAY_KANA[raw]) kana = SAY_KANA[raw];
  else if (ruby[raw]) kana = stripRubyReading(ruby[raw]);
  else kana = raw;
  kana = normKana(kana);
  if (KANJI.test(kana)) kana = kana.replace(WORD_RE, w => WORDS[w]);   // 数字＋助数詞（2人など）を読んだあとに残った漢字だけ
  return { text: cleanSpeech(raw), kana, kanaOk: !KANJI.test(kana) };
}
