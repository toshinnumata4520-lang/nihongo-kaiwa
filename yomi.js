function readLatin(s) {
  s = s.replace(/[Ａ-Ｚａ-ｚ]/g, c => String.fromCharCode(c.charCodeAt(0) - 0xFEE0));
  return s.replace(/Wi-Fi|No\.(?=\s*\d)|[A-Za-z]+/g, w => EN_WORD[w] ?? [...w.toUpperCase()].map(c => LETTER[c] || "").join(""));
}

const CIRCLED = "①②③④⑤⑥⑦⑧⑨⑩";
// 記号・出典・絵文字など、声に出さないものを外し、区切りは「、」にする（AIの声に渡す文と、読みの両方に使う）
export function cleanSpeech(s) {
  return String(s ?? "")
    .replace(/📖[^\n。]*|（?(?:出典|参考)[:：][^）\n]*）?/g, "")              // 出典（📖 p.12 など）
    .replace(/[\u{1F000}-\u{1FAFF}\u{2600}-\u{27BF}\u{FE0F}\u{200D}]/gu, "")  // 絵文字
    .replace(/ヒヤリ・ハット/g, "ヒヤリハット")                                // 1つの言葉として続けて読む
    .replace(/[①-⑩]/g, c => `${CIRCLED.indexOf(c) + 1}、`)                    // ①→「1、」（数字はあとで読みにする）
    .replace(/\r?\n+/g, (m, i, all) => /[。、！？!?」）]$/.test(all.slice(0, i)) ? " " : "。")
    // かぎかっこ：前に言葉があれば少し間をあけ、うしろに助詞（と・は・を…）が続くときは間をあけない（「あれ」は → あれは）
    .replace(/(^|.)[「『【]/g, (m, a) => !a || /[\s、。！？!?（(「『]/.test(a) ? a : a + "、")
    .replace(/[」』】](?=[とはをがのもでにって])/g, "").replace(/[」』】]/g, "、")
    .replace(/（([ぁ-んァ-ヶー]+)）(?=[^ぁ-ん]|$)/g, (m, r, i, all) => KANJI.test(all[i - 1] || "") ? "" : `、${r}、`) // 漢字のあとの（よみ）は読まない
    .replace(/[（(]/g, "、").replace(/[）)](?=[とはをがのもでにって])/g, "").replace(/[）)]/g, "、")
    .replace(/[・／/]/g, "、").replace(/[＝=]/g, "は、").replace(/…+|‥+/g, "、")   // A＝B は「AはB」と読む
    .replace(/(^|[^\d\s])\s*[〜～](?!\s*\d)/g, "$1なになに")                       // 「〜は ご遠慮ください」の〜（数の範囲の〜はあとで「から」）
    .replace(/[※＊*＃#→⇒▶▷◆◇■□●○★☆]/g, " ")
    .replace(/、\s*([、。！？!?])/g, "$1").replace(/([。！？!?])\s*、/g, "$1").replace(/、{2,}/g, "、")
    .replace(/^[\s、]+|[\s、]+$/g, "").replace(/[ \t　]{2,}/g, " ");
}
// 読み（ひらがな・カタカナ）を声に出す形に：数字・英字・記号を読みに直す
export function normKana(s) {
  s = cleanSpeech(s);
  s = readNumbers(s);
  s = s.replace(/[〜～]/g, "から");
  s = readLatin(s);
  s = s.replace(/[+＋]/g, "たす").replace(/[×✕]/g, "かける").replace(/[÷]/g, "わる");
  return s.replace(/、\s*([、。！？!?])/g, "$1").replace(/、{2,}/g, "、").replace(/^[\s、]+/, "");
}
